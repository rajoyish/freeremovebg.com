#!/usr/bin/env node
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, "..");

// Must match DEFAULT_LANG and LANG_COOKIE in src/i18n/config.ts. Both are
// emitted into worker/region-map.js so the Worker and the browser agree on the
// cookie the language switcher writes.
const DEFAULT_LANG = "en";
const LANG_COOKIE = "lang";

const languages = JSON.parse(
  await readFile(resolve(ROOT, "src/i18n/languages.json"), "utf8"),
);

const regionEntries = [];
for (const lang of languages) {
  if (lang.code === DEFAULT_LANG) continue;
  for (const country of lang.countries) {
    regionEntries.push(`  ${JSON.stringify(country)}: ${JSON.stringify(lang.code)},`);
  }
}

const codes = languages.map((l) => `  ${JSON.stringify(l.code)},`).join("\n");

const out = `export const regionMap = {
${regionEntries.join("\n")}
};

export const supportedCodes = [
${codes}
];

export const defaultLang = ${JSON.stringify(DEFAULT_LANG)};

export const langCookie = ${JSON.stringify(LANG_COOKIE)};
`;

await writeFile(resolve(ROOT, "worker/region-map.js"), out, "utf8");
console.log("✅ Wrote worker/region-map.js");

// ---------------------------------------------------------------------------
// Use-case slug redirects.
//
// src/i18n/slugs.ts moved the localized use-case pages from the English slug to
// a translated one, and those English URLs were live and indexed. Each gets a
// permanent redirect so its ranking and inbound links transfer to the new URL
// instead of dying at a 404. Generated rather than hand-written for the same
// reason region-map.js is: the slugs have exactly one source of truth.
// ---------------------------------------------------------------------------

// Parsed out of the TS module so the Worker table can never drift from the map
// the site builds its links from. Fragile to reformatting, cheap to re-run —
// the assertion below fails the build if the shape stops matching.
const slugsSrc = await readFile(resolve(ROOT, "src/i18n/slugs.ts"), "utf8");

const routesBlock = slugsSrc.match(
  /export const USE_CASE_ROUTES[^=]*=\s*\{([\s\S]*?)\n\};/,
)?.[1];
if (!routesBlock) {
  throw new Error("Could not parse USE_CASE_ROUTES out of src/i18n/slugs.ts");
}

const renamedLangs = JSON.parse(
  slugsSrc
    .match(/export const RENAMED_USE_CASE_LANGS = (\[[^\]]*\])/)?.[1]
    ?.replace(/'/g, '"')
    ?.replace(/,\s*\]/, "]") ?? "[]",
);

const redirectEntries = [];
let currentLang = null;
for (const line of routesBlock.split("\n")) {
  const langMatch = line.match(/^\s{2}(\w+):\s*\{/);
  if (langMatch) {
    currentLang = langMatch[1];
    continue;
  }
  const slugMatch = line.match(/^\s{4}"([^"]+)":\s*"([^"]+)"/);
  if (slugMatch && currentLang && renamedLangs.includes(currentLang)) {
    const [, english, localized] = slugMatch;
    // Both forms. A live page gets slashless -> slashed normalized for free by
    // the asset layer, but a retired slug has no asset to normalize against, so
    // the bare form would 404 instead of redirecting.
    redirectEntries.push(
      `/${currentLang}/${english} /${currentLang}/${localized}/ 301`,
      `/${currentLang}/${english}/ /${currentLang}/${localized}/ 301`,
    );
  }
}

if (renamedLangs.length && redirectEntries.length === 0) {
  throw new Error(
    "RENAMED_USE_CASE_LANGS is non-empty but no redirects were parsed — " +
      "USE_CASE_ROUTES formatting probably changed.",
  );
}

const redirects = `# Generated by scripts/gen-region-map.mjs — do not edit.
#
# Cloudflare Workers static-asset redirects, parsed by the ASSETS binding the
# same way public/_headers is, and applied before not_found_handling. The
# Worker itself cannot serve these: run_worker_first only covers "/" and
# "/api/count", so an unmatched asset elsewhere hits the 404 page without ever
# invoking it.

# @astrojs/sitemap writes sitemap-index.xml, but /sitemap.xml is the URL that
# was submitted to Search Console and linked from robots.txt for months.
/sitemap.xml /sitemap-index.xml 301

# Localized use-case pages moved from the English slug to a translated one
# (src/i18n/slugs.ts). These URLs were live and indexed, so each gets a 301 and
# its ranking follows the page instead of dying at a 404.

${redirectEntries.join("\n")}
`;

await writeFile(resolve(ROOT, "public/_redirects"), redirects, "utf8");
console.log(`✅ Wrote public/_redirects (${redirectEntries.length} redirects)`);
